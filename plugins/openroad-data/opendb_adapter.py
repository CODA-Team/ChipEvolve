"""OpenDB extraction plan.

The adapter invokes the native OpenROAD/OpenDB Tcl API. It does not parse ODB
bytes itself. The generated snapshot contains identities and physical facts;
the ODB and the extractor receipt remain raw evidence in the run.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def prepare(inputs: dict[str, Any], workspace: Path) -> dict[str, Any]:
    odb_path = _relative(inputs, "odb_path")
    output_name = _output_name(inputs)
    metadata = _metadata(inputs, "route")
    script = workspace / "opendb_extract.tcl"
    script.write_text(_script(odb_path, output_name, metadata), encoding="utf-8")
    binary = inputs.get("openroad_bin", "openroad")
    if not isinstance(binary, str) or not binary:
        raise ValueError("inputs.openroad_bin must be a non-empty string")
    return {
        "command": [binary, "-no_init", "-no_splash", "-exit", str(script)],
        "output_directory": output_name,
        "script_path": script.name,
    }


def _relative(inputs: dict[str, Any], name: str) -> str:
    value = inputs.get(name)
    if not isinstance(value, str) or not value or value.startswith("/") \
            or ".." in Path(value).parts:
        raise ValueError(f"inputs.{name} must be a relative staged path")
    return value


def _output_name(inputs: dict[str, Any]) -> str:
    value = inputs.get("output_directory", "query-data")
    if not isinstance(value, str) or not value or value.startswith("/") \
            or ".." in Path(value).parts:
        raise ValueError("inputs.output_directory must be a relative path")
    return value


def _metadata(inputs: dict[str, Any], stage: str) -> dict[str, str]:
    result = {key: inputs.get(key) for key in (
        "snapshot_id", "design_id", "revision_id", "run_id", "created_at")}
    result["stage"] = inputs.get("stage", stage)
    missing = [key for key, value in result.items() if not isinstance(value, str) or not value]
    if missing:
        raise ValueError(f"inputs missing snapshot fields: {', '.join(missing)}")
    return {key: str(value) for key, value in result.items()}


def _tcl(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    escaped = escaped.replace("[", "\\[").replace("]", "\\]")
    escaped = escaped.replace("$", "\\$")
    return f'"{escaped}"'


def _script(odb_path: str, output_name: str, metadata: dict[str, str]) -> str:
    meta = " ".join(f"{key} {_tcl(value)}" for key, value in metadata.items())
    return f'''# Generated by openroad-data/opendb_adapter.py.
proc json_q {{value}} {{
  set value [string map [list "\\\\" "\\\\\\\\" "\\\"" "\\\\\\\"" "\\n" "\\\\n" "\\r" "\\\\r" "\\t" "\\\\t"] $value]
  return "\\\"$value\\\""
}}
proc json_obj {{args}} {{
  set out "{{"
  set first 1
  foreach {{key value}} $args {{
    if {{!$first}} {{ append out "," }}
    append out [json_q $key] ":" $value
    set first 0
  }}
  append out "}}"
  return $out
}}
proc json_array {{args}} {{
  return "\\[[join $args ,]\\]"
}}
proc db_pin_geometry {{boxes coordinate_space}} {{
  set items [list]
  foreach box $boxes {{
    if {{[$box isVia]}} {{
      set via_name ""
      set bottom_layer ""
      set top_layer ""
      set tech_via [$box getTechVia]
      if {{$tech_via ne "NULL"}} {{
        set via_name [$tech_via getName]
        set bottom_layer [[$tech_via getBottomLayer] getName]
        set top_layer [[$tech_via getTopLayer] getName]
      }}
      lappend items [json_obj geometry_type [json_q via] \
          coordinate_space [json_q $coordinate_space] via [json_q $via_name] \
          bottom_layer [json_q $bottom_layer] top_layer [json_q $top_layer] \
          x [$box xMin] y [$box yMin]]
    }} else {{
      set layer [$box getTechLayer]
      if {{$layer eq "NULL"}} {{ continue }}
      lappend items [json_obj geometry_type [json_q rect] \
          coordinate_space [json_q $coordinate_space] layer [json_q [$layer getName]] \
          x_min [$box xMin] y_min [$box yMin] x_max [$box xMax] y_max [$box yMax]]
    }}
  }}
  return [json_array {{*}}$items]
}}
proc write_json {{path value}} {{
  set fd [open $path a]
  puts $fd $value
  close $fd
}}
set out [file normalize {_tcl(output_name)}]
file mkdir $out
foreach file {{objects.jsonl relations.jsonl markers.jsonl}} {{
  set fd [open [file join $out $file] w]
  close $fd
}}
set snapshot [json_obj snapshot_id [json_q {_tcl(metadata['snapshot_id'])}] \
  design_id [json_q {_tcl(metadata['design_id'])}] \
  revision_id [json_q {_tcl(metadata['revision_id'])}] \
  run_id [json_q {_tcl(metadata['run_id'])}] \
  stage [json_q {_tcl(metadata['stage'])}] \
  created_at [json_q {_tcl(metadata['created_at'])}] schema_version 3]
set fd [open [file join $out manifest.json] w]
puts $fd $snapshot
close $fd
set fd [open [file join $out summary.json] w]
puts $fd [json_obj snapshot $snapshot]
close $fd
read_db {_tcl(odb_path)}
set source_evidence [json_array [json_obj artifact_kind [json_q raw_design_database] \
    logical_path [json_q {_tcl(odb_path)}] source_type [json_q opendb]]]
set db [ord::get_db]
set chip [$db getChip]
set block [$chip getBlock]
if {{$block eq "NULL"}} {{ error "ODB has no block" }}
foreach inst [$block getInsts] {{
  set native_id [$inst getId]
  set object_id "inst:$native_id"
  set master [$inst getMaster]
  lassign [$inst getLocation] loc_x loc_y
  set bbox [$inst getBBox]
  set attributes [json_obj native_id [json_q $native_id] \
      master [json_q [$master getName]] orientation [json_q [$inst getOrient]]]
  set entity [json_obj object_id [json_q $object_id] snapshot_id [json_q {_tcl(metadata['snapshot_id'])}] \
      kind [json_q instance] name [json_q [$inst getName]] attributes $attributes]
  write_json [file join $out objects.jsonl] $entity
  set physical [json_obj object_id [json_q $object_id] snapshot_id [json_q {_tcl(metadata['snapshot_id'])}] \
      instance_name [json_q [$inst getName]] x $loc_x y $loc_y \
      bbox [json_obj x_min [$bbox xMin] y_min [$bbox yMin] x_max [$bbox xMax] y_max [$bbox yMax]] \
      geometry [json_array [json_obj geometry_type [json_q rect] \
          x_min [$bbox xMin] y_min [$bbox yMin] x_max [$bbox xMax] y_max [$bbox yMax]]] \
      routing [json_array] evidence $source_evidence]
  write_json [file join $out markers.jsonl] $physical
  foreach iterm [$inst getITerms] {{
    set pin_id "iterm:[$iterm getId]"
    set mterm [$iterm getMTerm]
    set net [$iterm getNet]
    set net_id ""
    if {{$net ne "NULL"}} {{ set net_id "net:[$net getId]" }}
    set pin_geometry [list]
    foreach mpin [$mterm getMPins] {{
      foreach box [$mpin getGeometry] {{ lappend pin_geometry $box }}
    }}
    set geometry [db_pin_geometry $pin_geometry master]
    set pin [json_obj object_id [json_q $pin_id] snapshot_id [json_q {_tcl(metadata['snapshot_id'])}] \
        kind [json_q pin] name [json_q "[$inst getName]/[$mterm getName]"] \
        parent_id [json_q $object_id] attributes [json_obj native_id [json_q [$iterm getId]] \
        geometry $geometry]]
    write_json [file join $out objects.jsonl] $pin
    write_json [file join $out markers.jsonl] [json_obj object_id [json_q $pin_id] \
        snapshot_id [json_q {_tcl(metadata['snapshot_id'])}] pin_name [json_q "[$inst getName]/[$mterm getName]"] \
        geometry $geometry evidence $source_evidence]
    write_json [file join $out relations.jsonl] [json_obj relation_id [json_q "pin-inst:$pin_id"] \
        snapshot_id [json_q {_tcl(metadata['snapshot_id'])}] subject_id [json_q $pin_id] \
        predicate [json_q belongs_to] object_id [json_q $object_id] attributes [json_obj]]
    if {{$net_id ne ""}} {{
      write_json [file join $out relations.jsonl] [json_obj relation_id [json_q "pin-net:$pin_id"] \
          snapshot_id [json_q {_tcl(metadata['snapshot_id'])}] subject_id [json_q $pin_id] \
          predicate [json_q connected_to] object_id [json_q $net_id] attributes [json_obj]]
    }}
  }}
}}
foreach bterm [$block getBTerms] {{
  set pin_id "bterm:[$bterm getId]"
  set net [$bterm getNet]
  set net_id ""
  if {{$net ne "NULL"}} {{ set net_id "net:[$net getId]" }}
  set pin_geometry [list]
  foreach bpin [$bterm getBPins] {{
    foreach box [$bpin getBoxes] {{ lappend pin_geometry $box }}
  }}
  set geometry [db_pin_geometry $pin_geometry block]
  set pin [json_obj object_id [json_q $pin_id] snapshot_id [json_q {_tcl(metadata['snapshot_id'])}] \
      kind [json_q pin] name [json_q [$bterm getName]] \
      attributes [json_obj native_id [json_q [$bterm getId]] geometry $geometry]]
  write_json [file join $out objects.jsonl] $pin
  write_json [file join $out markers.jsonl] [json_obj object_id [json_q $pin_id] \
      snapshot_id [json_q {_tcl(metadata['snapshot_id'])}] pin_name [json_q [$bterm getName]] \
      geometry $geometry evidence $source_evidence]
  if {{$net_id ne ""}} {{
    write_json [file join $out relations.jsonl] [json_obj relation_id [json_q "pin-net:$pin_id"] \
        snapshot_id [json_q {_tcl(metadata['snapshot_id'])}] subject_id [json_q $pin_id] \
        predicate [json_q connected_to] object_id [json_q $net_id] attributes [json_obj]]
  }}
}}
foreach net [$block getNets] {{
  set net_id "net:[$net getId]"
  set net_entity [json_obj object_id [json_q $net_id] snapshot_id [json_q {_tcl(metadata['snapshot_id'])}] \
      kind [json_q net] name [json_q [$net getName]] attributes [json_obj native_id [json_q [$net getId]]]]
  write_json [file join $out objects.jsonl] $net_entity
  set routing [json_array]
  set wire [$net getWire]
  if {{$wire ne "NULL"}} {{
    set routing_items [list]
    set iterator [odb::new_dbWirePathItr]
    set path [odb::new_dbWirePath]
    set shape [odb::new_dbWirePathShape]
    $iterator begin $wire
    while {{[$iterator getNextPath $path]}} {{
      if {{![ $iterator getNextShape $shape]}} {{ break }}
      set db_shape [odb::dbWirePathShape_shape_get $shape]
      if {{[odb::dbShape_isSegment $db_shape]}} {{
        set layer [odb::dbShape_getTechLayer $db_shape]
        set item [json_obj routing_type [json_q segment] wire_id [json_q [$wire getId]] \
            layer [json_q [$layer getName]] x_min [odb::dbShape_xMin $db_shape] \
            y_min [odb::dbShape_yMin $db_shape] x_max [odb::dbShape_xMax $db_shape] \
            y_max [odb::dbShape_yMax $db_shape]]
        lappend routing_items $item
      }} elseif {{[odb::dbShape_isVia $db_shape]}} {{
        set via [odb::dbShape_getTechVia $db_shape]
        set xy [odb::dbShape_getViaXY $db_shape]
        lassign $xy via_x via_y
        set item [json_obj routing_type [json_q via] wire_id [json_q [$wire getId]] \
            via [json_q [$via getName]] x $via_x y $via_y \
            bottom_layer [json_q [[$via getBottomLayer] getName]] \
            top_layer [json_q [[$via getTopLayer] getName]]]
        lappend routing_items $item
      }}
    }}
    set routing [json_array {{*}}$routing_items]
  }}
  write_json [file join $out markers.jsonl] [json_obj object_id [json_q $net_id] \
      snapshot_id [json_q {_tcl(metadata['snapshot_id'])}] geometry [json_array] routing $routing evidence $source_evidence]
}}
set fd [open [file join $out coverage.json] w]
puts $fd [json_obj source [json_q opendb] instances [json_q parsed] pins [json_q parsed] nets [json_q parsed] \
    location [json_q parsed] geometry [json_q partial] routing [json_q parsed]]
close $fd
'''
